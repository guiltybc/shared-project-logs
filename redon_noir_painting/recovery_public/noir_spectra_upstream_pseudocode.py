
# NOIR-SPECTRA 上流工程
# 創作判断モデル Ver0.2（概念実装）
#
# 材料 = 辞書（dict）
# 材料配列 = 辞書のリスト（list）
#
# 創作判断の関数は未実装。
# AIによる判断を想定した擬似Pythonコード。


# ========================================
# 1. 文章の理解と背景調査
# ========================================

文章 = 入力文章

内容 = 文章を把握する(文章)
背景 = 検索エンジンで背景調査する(文章)


# ========================================
# 2. 材料の格納形式
# ========================================

def 材料を作成(
    ID,
    名前,
    原型=None,
    由来="原文",
    親ID=None
):
    return {
        "ID": ID,
        "名前": 名前,

        # 原文に登場したもの、または元となった材料
        "原型": 原型 or 名前,

        # 原文・背景調査・異化からの派生など
        "由来": 由来,
        "親ID": 親ID,

        # 現在の造形状態
        "形態": 名前,
        "状態": "未処理",
        "異化履歴": [],

        # 意味と役割
        "意味": [],
        "機能": [],

        # 他の材料との関係
        "関係": [],

        # 構図上の情報
        "位置": None,
        "向き": None,
        "大きさ": None,

        # 採用状態
        "採用": True,
        "削除理由": None
    }


# ========================================
# 3. 登場候補をすべて配列化
# ========================================

候補 = 候補材料を列挙する(内容, 背景)

材料配列 = []

for i, 名前 in enumerate(候補):
    材料配列.append(
        材料を作成(
            ID=f"M{i+1}",
            名前=名前
        )
    )


# ========================================
# 4. 創作ループ
# ========================================

最大反復回数 = 10

for 回数 in range(最大反復回数):

    次の材料配列 = []

    for 材料 in 材料配列:

        # 非採用材料も再検討可能にする
        if not 材料["採用"]:
            if 復活すべき(材料, 内容):
                材料["採用"] = True
                材料["削除理由"] = None
            else:
                次の材料配列.append(材料)
                continue

        # --------------------------------
        # A. 削除の判断
        # --------------------------------

        if 削除すべき(材料, 内容):
            材料["採用"] = False
            材料["削除理由"] = 削除理由を記録する(材料)

            # 完全削除せず、配列に保持する
            次の材料配列.append(材料)
            continue

        # --------------------------------
        # B. 異化の判断
        # --------------------------------

        if 異化すべき(材料, 内容):

            異化結果 = 異化する(材料, 内容)

            # 元の状態を履歴へ保存
            材料["異化履歴"].append({
                "以前の形態": 材料["形態"],
                "新しい形態": 異化結果["形態"],
                "理由": 異化結果["理由"]
            })

            # 異化後の姿・意味・機能を継承
            材料["形態"] = 異化結果["形態"]
            材料["意味"] = 異化結果["意味"]
            材料["機能"] = 異化結果["機能"]
            材料["状態"] = "異化済み"

        else:
            if 材料["状態"] == "未処理":
                材料["状態"] = "原型維持"

        # --------------------------------
        # C. 新しい材料の派生
        # --------------------------------

        次の材料配列.append(材料)

        if 新しい構造が生まれた(材料):

            派生候補 = 派生材料を抽出する(材料)

            for 新材料名 in 派生候補:

                新材料 = 材料を作成(
                    ID=新しいIDを発行する(),
                    名前=新材料名,
                    原型=新材料名,
                    由来="異化からの派生",
                    親ID=材料["ID"]
                )

                # 新材料も次のループで検討する
                次の材料配列.append(新材料)

    # ------------------------------------
    # D. 材料間の関係と配置
    # ------------------------------------

    採用材料 = [
        材料 for 材料 in 次の材料配列
        if 材料["採用"]
    ]

    構図 = 構成する(採用材料)

    # 構図で決めた位置・向き・大きさ・関係を
    # 各材料の辞書にも反映する
    配置情報を更新する(採用材料, 構図)

    # ------------------------------------
    # E. 全体評価
    # ------------------------------------

    評価 = {
        "概要": 文章の概要が伝わる(構図, 内容),
        "本質": 本質がブレていない(構図, 内容),
        "過密": 説明過多ではない(構図),
        "空間": 空間的に成立する(構図),
        "余白": 余白が適切である(構図)
    }

    # 次のループへ渡す状態を確定
    材料配列 = 次の材料配列

    if all(評価.values()):
        break

    # 問題があれば、現在の状態から再構成
    # 異化済み材料は異化済みのまま引き継ぐ


# ========================================
# 5. 描画AIへ引き渡す
# ========================================

描画AIに渡す(
    構図=構図,
    材料=[m for m in 材料配列 if m["採用"]]
)
